/// A piece of input text.
enum TextToken<'a> {
    Word(&'a str),
    Number(&'a str),
    Punctuation(char),
}

/// Split text into words, numbers and punctuation.
///
/// Words may contain internal apostrophes or hyphens (eg. "it's", "well-known").
/// Numbers may contain commas between digit groups and a decimal point.
fn split_text(text: &str) -> Vec<TextToken<'_>> {
    let chars: Vec<(usize, char)> = text.char_indices().collect();
    let char_at = |i: usize| chars.get(i).map(|(_, c)| *c);
    let byte_pos = |i: usize| chars.get(i).map(|(pos, _)| *pos).unwrap_or(text.len());

    let mut tokens = Vec::new();
    let mut i = 0;
    while let Some(c) = char_at(i) {
        let start = i;
        if c.is_alphabetic() {
            i += 1;
            while let Some(c) = char_at(i) {
                let joins_letters = matches!(c, '\'' | '’' | '-')
                    && char_at(i + 1).is_some_and(|next| next.is_alphabetic());
                if c.is_alphabetic() || joins_letters {
                    i += 1;
                } else {
                    break;
                }
            }
            tokens.push(TextToken::Word(&text[byte_pos(start)..byte_pos(i)]));
        } else if c.is_ascii_digit() {
            let mut seen_point = false;
            i += 1;
            while let Some(c) = char_at(i) {
                let next_is_digit = char_at(i + 1).is_some_and(|next| next.is_ascii_digit());
                if c.is_ascii_digit() || (c == ',' && next_is_digit) {
                    i += 1;
                } else if c == '.' && next_is_digit && !seen_point {
                    seen_point = true;
                    i += 1;
                } else {
                    break;
                }
            }
            tokens.push(TextToken::Number(&text[byte_pos(start)..byte_pos(i)]));
        } else {
            if PUNCTUATION.contains(c) {
                tokens.push(TextToken::Punctuation(c));
            }
            i += 1;
        }
    }
    tokens
}

/// Convert a non-negative integer to English words (eg. 123 => "one hundred
/// twenty three").
fn cardinal_words(mut n: u64) -> Vec<&'static str> {
    const ONES: [&str; 20] = [
        "zero",
        "one",
        "two",
        "three",
        "four",
        "five",
        "six",
        "seven",
        "eight",
        "nine",
        "ten",
        "eleven",
        "twelve",
        "thirteen",
        "fourteen",
        "fifteen",
        "sixteen",
        "seventeen",
        "eighteen",
        "nineteen",
    ];
    const TENS: [&str; 10] = [
        "", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety",
    ];
    const SCALES: [&str; 5] = ["", "thousand", "million", "billion", "trillion"];

    if n == 0 {
        return vec![ONES[0]];
    }

    // Split into groups of three digits, least significant first.
    let mut groups = Vec::new();
    while n > 0 {
        groups.push((n % 1000) as usize);
        n /= 1000;
    }

    let mut words = Vec::new();
    for (scale, &group) in groups.iter().enumerate().rev() {
        if group == 0 {
            continue;
        }
        let (hundreds, rest) = (group / 100, group % 100);
        if hundreds > 0 {
            words.extend([ONES[hundreds], "hundred"]);
        }
        if rest >= 20 {
            words.push(TENS[rest / 10]);
            if rest % 10 > 0 {
                words.push(ONES[rest % 10]);
            }
        } else if rest > 0 {
            words.push(ONES[rest]);
        }
        if scale > 0 {
            words.push(SCALES[scale]);
        }
    }
    words
}

/// Convert a year such as 1999 to English words (eg. "nineteen ninety nine").
fn year_words(year: u64) -> Vec<&'static str> {
    let (century, rest) = (year / 100, year % 100);
    let mut words = match (century % 10, rest) {
        // eg. 2000 => "two thousand", 2005 => "two thousand five"
        (0, _) if rest < 10 => return cardinal_words(year),
        // eg. 1900 => "nineteen hundred"
        (_, 0) => return [cardinal_words(century), vec!["hundred"]].concat(),
        _ => cardinal_words(century),
    };
    // eg. 1905 => "nineteen oh five"
    if rest < 10 {
        words.push("oh");
    }
    words.extend(cardinal_words(rest));
    words
}

/// Convert a number such as "1,234.5" to English words.
///
/// Four-digit integers written without commas between 1100 and 2999 are read
/// as years.
fn number_words(number: &str) -> Vec<&'static str> {
    let digit_words = |digits: &str| -> Vec<&'static str> {
        digits
            .chars()
            .filter_map(|c| c.to_digit(10))
            .flat_map(|d| cardinal_words(d as u64))
            .collect()
    };

    let has_commas = number.contains(',');
    let number = number.replace(',', "");
    let (integer, fraction) = number.split_once('.').unwrap_or((&number, ""));

    let is_year = |n: u64| fraction.is_empty() && integer.len() == 4 && (1100..3000).contains(&n);

    // Read very long numbers digit by digit.
    let mut words = match integer.parse::<u64>() {
        Ok(n) if !has_commas && is_year(n) => year_words(n),
        Ok(n) if n < 1_000_000_000_000_000 => cardinal_words(n),
        _ => digit_words(integer),
    };
    if !fraction.is_empty() {
        words.push("point");
        words.extend(digit_words(fraction));
    }
    words
}

/// Character-level BART model which predicts the phonemes of a word.
///
/// This is the fallback for words that are not in the lexicon. The model is
/// exported to ONNX from the PyTorch weights in the model repository using
/// `export-kitten-g2p.py`.
struct G2pModel {
    encoder: Model,
    decoder: Model,

    /// Map of grapheme to input token ID.
    graphemes: HashMap<char, i32>,

    /// Map of output token ID to phoneme. The first four IDs are special
    /// tokens.
    phonemes: Vec<char>,

    /// Maximum length of input and output sequences, including start and end
    /// tokens.
    max_len: usize,
}

/// Configuration of the G2P model, from its `config.json` file.
#[derive(serde_derive::Deserialize)]
struct G2pConfig {
    /// Characters for each input token ID.
    grapheme_chars: String,
    /// Characters for each output token ID.
    phoneme_chars: String,
    max_position_embeddings: usize,
    bos_token_id: i32,
    eos_token_id: i32,
}

impl G2pModel {
    /// Number of special token IDs at the start of the vocabularies.
    const N_SPECIAL_TOKENS: usize = 4;

    /// Load the model from a directory containing `config.json`,
    /// `g2p_encoder.onnx` and `g2p_decoder.onnx`.
    ///
    /// Returns `None` if the exported ONNX models are not present.
    fn load(dir: &Path) -> Result<Option<(Self, G2pConfig)>, Box<dyn Error>> {
        let encoder_path = dir.join("g2p_encoder.onnx");
        let decoder_path = dir.join("g2p_decoder.onnx");
        if !encoder_path.exists() || !decoder_path.exists() {
            return Ok(None);
        }
        let config: G2pConfig = read_json(&dir.join("config.json"))?;
        let graphemes = config
            .grapheme_chars
            .chars()
            .enumerate()
            .skip(Self::N_SPECIAL_TOKENS)
            .map(|(id, c)| (c, id as i32))
            .collect();
        let phonemes = config.phoneme_chars.chars().collect();
        let model = G2pModel {
            encoder: Model::load_file(encoder_path)?,
            decoder: Model::load_file(decoder_path)?,
            graphemes,
            phonemes,
            max_len: config.max_position_embeddings,
        };
        Ok(Some((model, config)))
    }

    /// Predict phonemes for a word.
    ///
    /// Characters which are not in the model's input vocabulary are ignored.
    fn predict(&self, word: &str, config: &G2pConfig) -> Result<String, Box<dyn Error>> {
        let ids: Vec<i32> = word
            .chars()
            .filter_map(|c| self.graphemes.get(&c).copied())
            .collect();

        let mut phonemes = String::new();

        // Process long words in pieces which fit in the model's context,
        // leaving room for the start and end tokens.
        for piece in ids.chunks(self.max_len - 2) {
            let mut input_ids = vec![config.bos_token_id];
            input_ids.extend(piece);
            input_ids.push(config.eos_token_id);
            let input_ids = NdTensor::from_data([1, input_ids.len()], input_ids);

            let [hidden] = self.encoder.run_n(
                [(self.encoder.node_id("input_ids")?, input_ids.into())].into(),
                [self.encoder.node_id("last_hidden_state")?],
                None,
            )?;
            let hidden: NdTensor<f32, 3> = hidden.try_into()?;

            // Greedy decoding. The end token is forced at the last position,
            // so up to `max_len - 1` tokens are generated.
            let mut output_ids = vec![config.bos_token_id];
            while output_ids.len() < self.max_len - 1 {
                let decoder_input = NdTensor::from_data([1, output_ids.len()], output_ids.clone());
                let [logits] = self.decoder.run_n(
                    [
                        (
                            self.decoder.node_id("decoder_input_ids")?,
                            decoder_input.into(),
                        ),
                        (
                            self.decoder.node_id("encoder_hidden_states")?,
                            hidden.view().into(),
                        ),
                    ]
                    .into(),
                    [self.decoder.node_id("logits")?],
                    None,
                )?;
                let logits: NdTensor<f32, 3> = logits.try_into()?;
                let last = logits.slice((0, output_ids.len() - 1));
                let next_id = last
                    .iter()
                    .enumerate()
                    .max_by(|(_, a), (_, b)| a.total_cmp(b))
                    .map(|(id, _)| id as i32)
                    .unwrap();
                if next_id == config.eos_token_id {
                    break;
                }
                output_ids.push(next_id);
            }

            phonemes.extend(
                output_ids
                    .iter()
                    .filter(|&&id| id as usize >= Self::N_SPECIAL_TOKENS)
                    .filter_map(|&id| self.phonemes.get(id as usize)),
            );
        }

        // Apply the same substitutions as the reference implementation, which
        // misaki also applies to its own lexicon.
        Ok(phonemes.replace('ɾ', "T").replace('ʔ', "t"))
    }
}

/// Converts English text to phonemes using a pronunciation lexicon.
///
/// This is a simplified version of the text front end used to train Kitten
/// TTS, which uses misaki (https://github.com/hexgrad/misaki) with CMUdict and
/// a neural grapheme-to-phoneme model as fallbacks for unknown words. Here the
/// CMUdict lexicon is used, together with misaki's pronunciations of common
/// function words, so some pronunciations may differ from the reference
/// implementation. Pronunciations of words that are not in the lexicon are
/// predicted using the G2P model if available, or otherwise spelled out
/// letter by letter. Text normalization is limited to reading out numbers.
struct Phonemizer {
    /// Map of lower-case word to phonemes.
    lexicon: HashMap<String, String>,

    /// Model for predicting phonemes of words not in the lexicon.
    g2p: Option<(G2pModel, G2pConfig)>,
}

/// How the phonemes for a word which is not in the lexicon were obtained.
enum WordSource {
    /// Predicted by the G2P model.
    Predicted,
    /// Spelled out letter by letter.
    Spelled,
}

/// List of words which are not in the lexicon, with how their phonemes were
/// obtained.
type UnknownWords = Vec<(String, WordSource)>;

impl Phonemizer {
    /// Create a phonemizer using a lexicon, with [`FUNCTION_WORDS`] taking
    /// precedence over the lexicon's entries.
    fn new(mut lexicon: HashMap<String, String>, g2p: Option<(G2pModel, G2pConfig)>) -> Self {
        for (word, phonemes) in FUNCTION_WORDS {
            lexicon.insert(word.to_string(), phonemes.to_string());
        }
        Self { lexicon, g2p }
    }

    /// Return phonemes for a word, or `None` if it is not in the lexicon.
    fn lookup(&self, word: &str) -> Option<String> {
        if let Some(phonemes) = self.lexicon.get(word) {
            return Some(phonemes.clone());
        }

        // Handle possessives which are not in the lexicon.
        if let Some(stem) = word.strip_suffix("'s")
            && let Some(stem_phonemes) = self.lexicon.get(stem)
        {
            let suffix = match stem_phonemes.chars().last() {
                Some('p' | 't' | 'k' | 'f' | 'θ') => "s",
                Some('s' | 'z' | 'ʃ' | 'ʒ' | 'ʧ' | 'ʤ') => "ᵻz",
                _ => "z",
            };
            return Some(format!("{stem_phonemes}{suffix}"));
        }

        None
    }

    /// Return phonemes for a word.
    ///
    /// Words which are not in the lexicon are added to `unknown_words`
    /// together with how their phonemes were obtained.
    fn word_phonemes(
        &self,
        word: &str,
        unknown_words: &mut UnknownWords,
    ) -> Result<String, Box<dyn Error>> {
        let word = word.replace('’', "'");
        if let Some(phonemes) = self.lookup(&word.to_lowercase()) {
            return Ok(phonemes);
        }

        // Handle compound words by looking up each part.
        if word.contains('-') {
            let parts = word
                .split('-')
                .filter(|part| !part.is_empty())
                .map(|part| self.word_phonemes(part, unknown_words))
                .collect::<Result<Vec<_>, _>>()?;
            return Ok(parts.join(" "));
        }

        // Use the G2P model if available. This is case-sensitive, so the
        // original case is used.
        if let Some((g2p, config)) = &self.g2p {
            let phonemes = g2p.predict(word.trim_matches(['\'', '.']), config)?;
            if !phonemes.is_empty() {
                unknown_words.push((word, WordSource::Predicted));
                return Ok(phonemes);
            }
        }

        let phonemes = word
            .to_lowercase()
            .chars()
            .filter(|c| c.is_ascii_lowercase())
            .map(|c| LETTER_NAMES[(c as u8 - b'a') as usize])
            .collect::<Vec<_>>()
            .join(" ");
        unknown_words.push((word, WordSource::Spelled));
        Ok(phonemes)
    }

    /// Convert text to a string of phonemes.
    ///
    /// Words are separated by spaces, and punctuation is attached to the
    /// adjacent word, as in the phoneme strings used to train the model.
    /// Returns the phonemes and a list of words which were not in the lexicon,
    /// with how their phonemes were obtained.
    fn phonemize(&self, text: &str) -> Result<(String, UnknownWords), Box<dyn Error>> {
        let mut phonemes = String::new();
        let mut unknown_words = Vec::new();
        let mut in_quote = false;

        // Whether the next word should be separated from the previous output
        // by a space.
        let mut separate_next = false;

        let push_word = |phonemes: &mut String, word: &str, separate: &mut bool| {
            if word.is_empty() {
                return;
            }
            if *separate {
                phonemes.push(' ');
            }
            phonemes.push_str(word);
            *separate = true;
        };

        for token in split_text(text) {
            match token {
                TextToken::Word(word) => {
                    let word_phonemes = self.word_phonemes(word, &mut unknown_words)?;
                    push_word(&mut phonemes, &word_phonemes, &mut separate_next);
                }
                TextToken::Number(number) => {
                    for word in number_words(number) {
                        let word_phonemes = self.word_phonemes(word, &mut unknown_words)?;
                        push_word(&mut phonemes, &word_phonemes, &mut separate_next);
                    }
                }
                TextToken::Punctuation(c) => {
                    // Opening brackets and quotes attach to the following
                    // word. Other punctuation attaches to the preceding word.
                    let opening = match c {
                        '(' | '“' => true,
                        '"' => {
                            in_quote = !in_quote;
                            in_quote
                        }
                        _ => false,
                    };
                    if opening {
                        if separate_next {
                            phonemes.push(' ');
                        }
                        phonemes.push(c);
                        separate_next = false;
                    } else {
                        phonemes.push(c);
                        separate_next = true;
                    }
                }
            }
        }

        Ok((phonemes, unknown_words))
    }
}

/// Split a phoneme string into chunks of at most `max_len` characters.
///
/// Splits are made at sentence ends where possible, then at word boundaries.
fn chunk_phonemes(phonemes: &str, max_len: usize) -> Vec<String> {
    // Split into sentences, keeping the terminating punctuation.
    let mut sentences = Vec::new();
    let mut sentence = String::new();
    let mut chars = phonemes.chars().peekable();
    while let Some(c) = chars.next() {
        sentence.push(c);
        if matches!(c, '.' | '!' | '?' | '…') && chars.peek() == Some(&' ') {
            chars.next();
            sentences.push(std::mem::take(&mut sentence));
        }
    }
    if !sentence.is_empty() {
        sentences.push(sentence);
    }

    // Split sentences which are too long at word boundaries.
    let mut pieces = Vec::new();
    for sentence in sentences {
        let mut rest = sentence.as_str();
        while rest.chars().count() > max_len {
            let limit = rest.char_indices().nth(max_len).map(|(i, _)| i).unwrap();
            let split = rest[..limit].rfind(' ').filter(|&i| i > 0).unwrap_or(limit);
            pieces.push(rest[..split].to_string());
            rest = rest[split..].trim_start();
        }
        if !rest.is_empty() {
            pieces.push(rest.to_string());
        }
    }

    // Combine pieces into chunks of up to `max_len` characters.
    let mut chunks: Vec<String> = Vec::new();
    for piece in pieces {
        match chunks.last_mut() {
            Some(chunk) if chunk.chars().count() + 1 + piece.chars().count() <= max_len => {
                chunk.push(' ');
                chunk.push_str(&piece);
            }
            _ => chunks.push(piece),
        }
    }
    chunks
}

/// Convert a phoneme string to model input token IDs.
///
/// Characters which are not in the vocabulary are skipped.
fn encode_phonemes(phonemes: &str, vocab: &HashMap<String, i32>) -> Vec<i32> {
    let mut ids = vec![PAD_ID];
    let mut buf = [0u8; 4];
    ids.extend(
        phonemes
            .chars()
            .filter_map(|c| vocab.get(&*c.encode_utf8(&mut buf)).copied()),
    );
    ids.extend([END_ID, PAD_ID]);
    ids
}

/// Generate audio for one chunk of input token IDs.
///
/// `voice` is a `[max_len, style_dim]` tensor with one style vector per input
/// length. If `keep_start` is false, the pause generated for the initial token
/// is removed.
fn synthesize(
    model: &Model,
    voice: NdTensorView<f32, 2>,
    token_ids: &[i32],
    speed: f32,
    keep_start: bool,
) -> Result<Vec<f32>, Box<dyn Error>> {
    let style_idx = (token_ids.len() - 1).min(voice.size(0) - 1);
    let style = voice.slice((style_idx..style_idx + 1, ..));
    let tokens = NdTensor::from_data([1, token_ids.len()], token_ids.to_vec());
    let speed = NdTensor::from([speed]);

    let [waveform, durations] = model.run_n(
        [
            (model.node_id("input_ids")?, tokens.into()),
            (model.node_id("style")?, style.into()),
            (model.node_id("speed")?, speed.into()),
        ]
        .into(),
        [model.node_id("waveform")?, model.node_id("durations")?],
        None,
    )?;
    let waveform: NdTensor<f32, 1> = waveform.try_into()?;
    let durations: NdTensor<i32, 1> = durations.try_into()?;

    // `durations` gives the number of frames generated for each input token.
    // Remove the audio generated for the final token and, optionally, the
    // initial token, leaving one frame of each, as the reference
    // implementation does.
    let total_frames: i32 = durations.iter().sum();
    let samples_per_frame = (waveform.len() as f32 / total_frames.max(1) as f32)
        .round()
        .max(1.) as usize;
    let excess_samples = |frames: Option<&i32>| {
        (frames.copied().unwrap_or(0).max(1) as usize - 1) * samples_per_frame
    };
    let leading = if keep_start {
        0
    } else {
        excess_samples(durations.iter().next())
    };
    let trailing = excess_samples(durations.iter().next_back());

    let mut audio: Vec<f32> = waveform.iter().map(|x| x.clamp(-1., 1.)).collect();
    if leading + trailing + samples_per_frame < audio.len() {
        audio.truncate(audio.len() - trailing);
        audio.drain(..leading);
    }

    // Apply short (~5ms) fades at the start and end to avoid clicks.
    let fade_len = (audio.len() / 8).min(120);
    let audio_len = audio.len();
    for i in 0..fade_len {
        let scale = i as f32 / (fade_len - 1).max(1) as f32;
        audio[i] *= scale;
        audio[audio_len - 1 - i] *= scale;
    }

    Ok(audio)
}

/// Return the path of a file in the same directory as the model.
fn model_dir_file(model_path: &str, file: &str) -> PathBuf {
    Path::new(model_path)
        .parent()
        .unwrap_or(Path::new(""))
        .join(file)
}

/// Read a JSON file, with an error message that mentions where to get it.
fn read_json<T: serde::de::DeserializeOwned>(path: &Path) -> Result<T, Box<dyn Error>> {
    let json = std::fs::read_to_string(path).map_err(|err| {
        format!(
            "failed to read {}: {err}. Download it from \
             https://huggingface.co/KittenML/kitten-tts-2-mini",
            path.display()
        )
    })?;
    Ok(serde_json::from_str(&json)?)
}

/// Convert text to speech using Kitten TTS 2 Mini.
///
/// Download `kitten_tts_2_mini.onnx` (int8 weights) or
/// `kitten_tts_2_mini_int4.onnx` (int4 weights), `voices_en.npz`,
/// `vocab.json` and `g2p/cmu_misaki_us.json` from
/// https://huggingface.co/KittenML/kitten-tts-2-mini, keeping the same
/// directory layout. Then run with:
///
/// ```text
/// cargo run -p rten-examples -r --bin kitten_tts -- kitten_tts_2_mini.onnx voices_en.npz "Text to speak"
/// ```
///
/// This will generate an output audio file in `output.wav`. Use `--voice` to
/// choose a different voice (eg. "max", "otis"). The available English voices
/// are listed in the model's README.
///
/// The text is converted to phonemes using a pronunciation lexicon. To predict
/// pronunciations of words that are not in the lexicon, also download
/// `g2p/g2p_bart_en_us/` from the model repository and export it to ONNX:
///
/// ```text
/// python rten-examples/src/export-kitten-g2p.py g2p/g2p_bart_en_us
/// ```
///
/// Otherwise unknown words are spelled out. See [`Phonemizer`] for
/// limitations.
///
/// Most of the decoder's convolutions and the text encoder's matrix
/// multiplications run with int8 activations, which is significantly faster.
/// See [`DYNAMIC_QUANT_CONV_WEIGHTS`] and [`DYNAMIC_QUANT_MATMUL_WEIGHTS`].
fn main() -> Result<(), Box<dyn Error>> {
    let args: Args = argh::from_env();

    // Safety: No other threads have been started yet.
    unsafe {
        std::env::set_var("RTEN_CONV_DYNAMIC_QUANT", DYNAMIC_QUANT_CONV_WEIGHTS);
        std::env::set_var("RTEN_MATMUL_DYNAMIC_QUANT", DYNAMIC_QUANT_MATMUL_WEIGHTS);
    }

    // Read the lexicon while the model loads, as parsing it takes a while.
    let lexicon_path = args
        .lexicon
        .map(PathBuf::from)
        .unwrap_or_else(|| model_dir_file(&args.model, "g2p/cmu_misaki_us.json"));
    let lexicon = std::thread::spawn(move || {
        read_json::<HashMap<String, String>>(&lexicon_path).map_err(|err| err.to_string())
    });

    let model = ModelOptions::with_all_ops()
        .prepack_weights(true)
        .load_file(&args.model)?;

    let vocab_path = args
        .vocab
        .map(PathBuf::from)
        .unwrap_or_else(|| model_dir_file(&args.model, "vocab.json"));
    let vocab: HashMap<String, i32> = read_json(&vocab_path)?;

    let g2p_dir = args
        .g2p_model
        .map(PathBuf::from)
        .unwrap_or_else(|| model_dir_file(&args.model, "g2p/g2p_bart_en_us"));
    let g2p = G2pModel::load(&g2p_dir)?;
    let has_g2p = g2p.is_some();
    let lexicon = lexicon.join().expect("lexicon thread panicked")?;
    let phonemizer = Phonemizer::new(lexicon, g2p);

    let voice: Tensor<f32> =
        rten_serialize::npz::read_array_from_file(&args.voices, &args.voice)?.into_type()?;
    let voice: NdTensor<f32, 2> = voice.try_into()?;

    let text = args.text.as_deref().unwrap_or(DEFAULT_TEXT);
    let (phonemes, unknown_words) = phonemizer.phonemize(text)?;
    if args.verbose {
        println!("Phonemes: {phonemes}");
    }

    let words_from = |source: fn(&WordSource) -> bool| -> Vec<&str> {
        unknown_words
            .iter()
            .filter(|(_, src)| source(src))
            .map(|(word, _)| word.as_str())
            .collect()
    };
    let predicted = words_from(|src| matches!(src, WordSource::Predicted));
    if !predicted.is_empty() {
        println!("Words predicted by G2P model: {}", predicted.join(", "));
    }
    let spelled = words_from(|src| matches!(src, WordSource::Spelled));
    if !spelled.is_empty() {
        println!("Words spelled out: {}", spelled.join(", "));
        if !has_g2p {
            println!(
                "To predict pronunciations of unknown words, export the G2P model to {} \
                 using export-kitten-g2p.py",
                g2p_dir.display()
            );
        }
    }

    let gap_len = (CHUNK_GAP * SAMPLE_RATE as f32) as usize;
    let mut audio = Vec::new();
    for (i, chunk) in chunk_phonemes(&phonemes, MAX_PHONEMES).iter().enumerate() {
        let token_ids = encode_phonemes(chunk, &vocab);
        let keep_start = i == 0;
        if !keep_start {
            audio.extend(std::iter::repeat_n(0., gap_len));
        }
        audio.extend(synthesize(
            &model,
            voice.view(),
            &token_ids,
            args.speed,
            keep_start,
        )?);
    }

    let wav_file = BufWriter::new(File::create(&args.output)?);
    let mut wav_writer = WavWriter::new(
        wav_file,
        WavSpec {
            channels: 1,
            sample_rate: SAMPLE_RATE,
            bits_per_sample: 32,
            sample_format: SampleFormat::Float,
        },
    )?;
    for &sample in &audio {
        wav_writer.write_sample(sample)?;
    }
    wav_writer.finalize()?;

    if args.verbose {
        println!(
            "Wrote {:.2}s of audio to {}",
            audio.len() as f32 / SAMPLE_RATE as f32,
            args.output
        );
    }

    Ok(())
}
